'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const input = path.join(root, 'content/batch-001/approved.json');
const baselineFile = path.join(root, 'content/batch-004/baseline-260.json');
const output = path.join(root, 'miniprogram/data/curated-shapes.js');

function buildShapes(manifest, baseline) {
  const baselineIds = new Set(baseline.items.map(item => item.id));
  const byId = new Map(manifest.items.map(item => [item.id, item]));
  const metadata = new Map();
  const contentRoot = fs.realpathSync(path.join(root, 'content')) + path.sep;
  function sizeFor(item, visiting = new Set()) {
    if (!item || visiting.has(item.id)) throw new Error('封面引用不存在或形成循环');
    visiting.add(item.id);
    if (item.video && Number.isFinite(item.video.width) && Number.isFinite(item.video.height) && item.video.width > 0 && item.video.height > 0) return [item.video.width, item.video.height];
    const sourceId = item.imagePhotoIds && item.imagePhotoIds[0] || item.coverPhotoId;
    if (sourceId) return sizeFor(byId.get(sourceId), visiting);
    const source = item.sourceEvidence;
    const evidence = source && (source.imageSources && source.imageSources[0] || source);
    if (!evidence || typeof evidence.metadataFile !== 'string' || !evidence.pageid) throw new Error(item.id + ' 缺少首图的来源尺寸证据');
    const file = fs.realpathSync(path.resolve(root, evidence.metadataFile));
    if (!file.startsWith(contentRoot) || path.extname(file) !== '.json') throw new Error(item.id + ' 来源元数据必须位于 content 目录');
    if (!metadata.has(file)) metadata.set(file, JSON.parse(fs.readFileSync(file, 'utf8')));
    const records = metadata.get(file);
    const record = Array.isArray(records) && records.find(row => String(row.pageid) === String(evidence.pageid));
    const info = record && (record.imageinfo || record.videoinfo || [])[0];
    if (!info || !Number.isFinite(info.width) || !Number.isFinite(info.height) || info.width <= 0 || info.height <= 0) throw new Error(item.id + ' 的来源元数据没有有效宽高');
    const firstImage = item.images && item.images[0];
    if (firstImage && evidence.sourceUrl && firstImage.sourceUrl !== evidence.sourceUrl) throw new Error(item.id + ' 首图与尺寸证据对应的来源不一致');
    return [info.width, info.height];
  }
  const shapes = {};
  for (const item of manifest.items) if (!baselineIds.has(item.id)) shapes[item.id] = sizeFor(item);
  return shapes;
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(input, 'utf8'));
  const baseline = JSON.parse(fs.readFileSync(baselineFile, 'utf8'));
  const shapes = buildShapes(manifest, baseline);
  const source = "'use strict';\n// Generated by scripts/prepare-curated-shapes.js from approved cover metadata.\n// The original 260 records keep their existing shape hints and runtime data.\nmodule.exports = Object.freeze(" + JSON.stringify(shapes) + ');\n';
  fs.writeFileSync(output, source);
  process.stdout.write('已更新 ' + Object.keys(shapes).length + ' 条新增内容的封面尺寸提示。\n');
}

if (require.main === module) {
  try { main(); } catch (error) { process.stderr.write(error.message + '\n'); process.exitCode = 1; }
}

module.exports = { buildShapes };
